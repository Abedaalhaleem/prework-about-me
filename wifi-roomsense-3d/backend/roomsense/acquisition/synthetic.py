@dataclass
class Episode:
    """One labelled interval of the simulated timeline.

    ``params`` (all optional): ``links`` (affected link ids, default all),
    ``zone`` (MOTION region), ``strength``, ``position`` (STILL_PERSON),
    ``hinge`` (DOOR), ``point`` (NEAR_SENSOR_OUTSIDE), ``fraction``
    (PACKET_LOSS), ``speed_mps`` (walkers), ``label`` (ground-truth label).
    """

    t_start_s: float
    t_end_s: float
    kind: str
    params: dict[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if self.kind not in EPISODE_KINDS:
            raise ValueError(f"unknown episode kind {self.kind!r}")
        if not (0 <= self.t_start_s < self.t_end_s):
            raise ValueError("episode needs 0 <= t_start_s < t_end_s")

    def active(self, t: float) -> bool:
        return self.t_start_s <= t < self.t_end_s


@dataclass
class SyntheticScenario:
    """A simulated session: links, labelled episodes and a seed.

    Optional ``params`` (toy-model knobs, none calibrated to a real room):
    ``environment_seed`` (static multipath and clocks; default ``seed``),
    ``n_reflections`` (6), ``noise_std`` (0.6 int8 counts), ``gain_jitter``
    (0.03), ``timing_jitter_ms`` (1.0), ``target_amplitude`` (20 counts),
    ``carrier_hz``, ``clock_drift_ppm``, ``device_clock_start_us`` and
    ``counter_start`` (to exercise rollover handling).
    """

    name: str
    duration_s: float
    rate_hz: float
    links: list[tuple[str, str]]
    episodes: list[Episode]
    seed: int
    description: str = ""
    node_positions: dict[str, tuple[float, float, float]] = field(default_factory=dict)
    room_size_m: tuple[float, float] = SYNTHETIC_ROOM_SIZE_M
    zones: dict[str, tuple[float, float, float, float]] = field(default_factory=lambda: dict(SYNTHETIC_ZONES))
    params: dict[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if not (0 < self.duration_s <= 24 * 3600):
            raise ValueError("duration_s must be in (0, 86400]")
        if not (0 < self.rate_hz <= 1000):
            raise ValueError("rate_hz must be in (0, 1000]")
        if not self.links:
            raise ValueError("a scenario needs at least one link")
        self.links = [(str(t), str(r)) for t, r in self.links]
        if len(set(self.links)) != len(self.links):
            raise ValueError("duplicate link in scenario")
        for ep in self.episodes:
            if ep.t_end_s > self.duration_s + 1e-9:
                raise ValueError(f"episode {ep.kind} ends after the scenario")
            zone = ep.params.get("zone")
            if zone is not None and zone not in self.zones:
                raise ValueError(f"episode {ep.kind} refers to unknown zone {zone!r}")
        positions = dict(self.node_positions)
        txs = sorted({t for t, _ in self.links})
        rxs = sorted({r for _, r in self.links})
        w, d = self.room_size_m
        for i, t in enumerate(txs):
            positions.setdefault(t, (0.0, d * (i + 1) / (len(txs) + 1), BODY_HEIGHT_M))
        for i, r in enumerate(rxs):
            positions.setdefault(r, (w, d * (i + 1) / (len(rxs) + 1), BODY_HEIGHT_M))
        self.node_positions = {k: (float(v[0]), float(v[1]), float(v[2])) for k, v in positions.items()}

    def link_ids(self) -> list[str]:
        return [f"{t}->{r}" for t, r in self.links]

    def affected_links(self, ep: Episode) -> list[str]:
        wanted = ep.params.get("links")
        all_ids = self.link_ids()
        return all_ids if not wanted else [lid for lid in all_ids if lid in set(wanted)]

    def ground_truth(self) -> list[dict[str, Any]]:
        """Labelled intervals, for SOFTWARE TESTS only (simulated truth).

        Gaps not covered by any episode are returned as implicit ``EMPTY``
        intervals. ``motion_expected`` says what a motion detector should
        report if the software works (``None`` = no data expected, i.e.
        SENSOR_OFFLINE / UNKNOWN).
        """
        out: list[dict[str, Any]] = []
        for ep in sorted(self.episodes, key=lambda e: (e.t_start_s, e.t_end_s)):
            out.append(_truth_entry(self, ep, implicit=False))
        covered = sorted((e.t_start_s, e.t_end_s) for e in self.episodes)
        t = 0.0
        gaps: list[tuple[float, float]] = []
        for s, e in covered:
            if s > t + 1e-9:
                gaps.append((t, s))
            t = max(t, e)
        if t < self.duration_s - 1e-9:
            gaps.append((t, self.duration_s))
        for s, e in gaps:
            out.append(_truth_entry(self, Episode(s, e, EMPTY), implicit=True))
        out.sort(key=lambda d: (d["t_start_s"], d["t_end_s"]))
        return out


def _truth_entry(scn: SyntheticScenario, ep: Episode, *, implicit: bool) -> dict[str, Any]:
    label = ep.params.get("label")
    expected: bool | None
    note = ""
    if ep.kind == MOTION:
        label = label or ep.params.get("zone") or MOTION
        expected = True
    elif ep.kind == NEAR_SENSOR_OUTSIDE:
        label = label or "OUTSIDE_TARGET_ROOM"
        expected = True
        note = "Known limitation: motion outside the target room near a sensor also changes the CSI."
    elif ep.kind == STILL_PERSON:
        label = label or STILL_PERSON
        expected = False
        note = "Known limitation: a motionless person is expected to remain undetected."
    elif ep.kind == DOOR:
        label = label or DOOR
        expected = True
        note = "A moving door is motion; it is not a person."
    elif ep.kind == EMPTY:
        label = label or EMPTY
        expected = False
    else:  # DISCONNECT, PACKET_LOSS
        label = label or ep.kind
        expected = None
        note = "No motion label: data is missing or degraded (expect SENSOR_OFFLINE/UNKNOWN or degraded quality)."
    params = {k: v for k, v in ep.params.items() if isinstance(v, (str, int, float, bool, list, tuple))}
    return {
        "t_start_s": float(ep.t_start_s),
        "t_end_s": float(ep.t_end_s),
        "kind": ep.kind,
        "label": label,
        "links": scn.affected_links(ep),
        "motion_expected": expected,
        "implicit": implicit,
        "params": params,
        "note": note,
        "synthetic": True,
    }


