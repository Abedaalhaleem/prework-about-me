def _dist_point_segment(p: np.ndarray, a: np.ndarray, b: np.ndarray) -> float:
    ab = b - a
    denom = float(ab @ ab)
    s = 0.0 if denom == 0 else float(np.clip((p - a) @ ab / denom, 0.0, 1.0))
    return float(np.linalg.norm(p - (a + s * ab)))


class _Walker:
    """Piecewise-linear walk through random waypoints inside a rectangle."""

    def __init__(self, rng: np.random.Generator, region: tuple[float, float, float, float], speed: float,
                 duration: float) -> None:
        x0, x1, y0, y1 = region
        margin = 0.2
        if x1 - x0 > 2 * margin:
            x0, x1 = x0 + margin, x1 - margin
        if y1 - y0 > 2 * margin:
            y0, y1 = y0 + margin, y1 - margin
        pts = [np.array([rng.uniform(x0, x1), rng.uniform(y0, y1)])]
        length = 0.0
        needed = speed * duration + 1.0
        # Bounded: at most a few thousand waypoints even for long episodes.
        while length < needed and len(pts) < 5000:
            nxt = np.array([rng.uniform(x0, x1), rng.uniform(y0, y1)])
            step = float(np.linalg.norm(nxt - pts[-1]))
            if step < 0.3:
                continue
            pts.append(nxt)
            length += step
        self.pts = np.asarray(pts)
        seg = np.linalg.norm(np.diff(self.pts, axis=0), axis=1)
        self.cum = np.concatenate([[0.0], np.cumsum(seg)])
        self.speed = speed

    def position(self, t_rel: float) -> np.ndarray:
        s = min(max(t_rel, 0.0) * self.speed, float(self.cum[-1]))
        i = int(np.searchsorted(self.cum, s, side="right")) - 1
        i = min(max(i, 0), len(self.pts) - 2)
        seg_len = self.cum[i + 1] - self.cum[i]
        u = 0.0 if seg_len <= 0 else (s - self.cum[i]) / seg_len
        xy = self.pts[i] + u * (self.pts[i + 1] - self.pts[i])
        return np.array([xy[0], xy[1], BODY_HEIGHT_M])


@dataclass
class _LinkModel:
    index: int
    link_id: str
    tx_id: str
    rx_id: str
    tx: np.ndarray
    rx: np.ndarray
    d_los: float
    a_los: float
    los_delay: float
    refl_amp: np.ndarray  # complex amplitudes of static reflections
    refl_delay: np.ndarray
    gain: float  # model units -> int8 counts
    base_rssi: float
    drift_ppm: float
    dev0_us: int
    counter0: int
    offset_s: float
    h0_power: float = 0.0


def _build_link(scn: SyntheticScenario, idx: int, carrier_hz: float) -> _LinkModel:
    env_seed = int(scn.params.get("environment_seed", scn.seed))
    rng = np.random.default_rng([env_seed, 1, idx])
    tx_id, rx_id = scn.links[idx]
    tx = np.asarray(scn.node_positions[tx_id], dtype=np.float64)
    rx = np.asarray(scn.node_positions[rx_id], dtype=np.float64)
    d_los = max(float(np.linalg.norm(rx - tx)), 0.5)
    # Indoor-like delay spread: reflections 3-18 m longer than the direct
    # path (10-60 ns), which makes the channel frequency-selective across the
    # 20 MHz band as real ESP32 CSI is.
    n_refl = int(scn.params.get("n_reflections", 6))
    extra = rng.uniform(3.0, 18.0, n_refl)
    refl_amp = (
        (1.0 / d_los) * rng.uniform(0.3, 0.9, n_refl) * d_los / (d_los + extra) * 2.0
        * np.exp(1j * rng.uniform(0, 2 * np.pi, n_refl))
    )
    refl_delay = (d_los + extra) / SPEED_OF_LIGHT
    link = _LinkModel(
        index=idx,
        link_id=f"{tx_id}->{rx_id}",
        tx_id=tx_id,
        rx_id=rx_id,
        tx=tx,
        rx=rx,
        d_los=d_los,
        a_los=1.0 / d_los,
        los_delay=d_los / SPEED_OF_LIGHT,
        refl_amp=refl_amp,
        refl_delay=refl_delay,
        gain=1.0,
        base_rssi=-38.0 - 20.0 * math.log10(d_los),
        drift_ppm=float(scn.params.get("clock_drift_ppm", rng.uniform(-25.0, 25.0))),
        dev0_us=int(scn.params.get("device_clock_start_us", int(rng.integers(1_000_000, 1_000_000_000)))),
        counter0=int(scn.params.get("counter_start", 0)) & 0xFFFFFFFF,
        offset_s=idx / (len(scn.links) + 1) / scn.rate_hz,
    )
    f = carrier_hz + _K_VALID * SUBCARRIER_SPACING_HZ
    h0 = _static_response(link, f, los_factor=1.0)
    target = float(scn.params.get("target_amplitude", 20.0))
    link.gain = target / max(float(np.median(np.abs(h0))), 1e-12)
    link.h0_power = float(np.mean(np.abs(h0) ** 2))
    return link


def _paths(amp: np.ndarray, delay: np.ndarray, f: np.ndarray) -> np.ndarray:
    return np.sum(amp[:, None] * np.exp(-2j * np.pi * f[None, :] * delay[:, None]), axis=0)


def _static_response(link: _LinkModel, f: np.ndarray, *, los_factor: float) -> np.ndarray:
    los = link.a_los * los_factor * np.exp(-2j * np.pi * f * link.los_delay)
    return los + _paths(link.refl_amp, link.refl_delay, f)


class _EpisodeState:
    """Per-episode deterministic state shared by all links (one person/door)."""

    def __init__(self, scn: SyntheticScenario, idx: int, ep: Episode) -> None:
        self.ep = ep
        self.links = set(scn.affected_links(ep))
        rng = np.random.default_rng([scn.seed, 1000 + idx])
        self.phase = float(rng.uniform(0, 2 * np.pi))
        self.strength = float(ep.params.get("strength", {DOOR: 2.0, NEAR_SENSOR_OUTSIDE: 1.6}.get(ep.kind, 1.0)))
        self.fraction = float(ep.params.get("fraction", 0.3))
        w, d = scn.room_size_m
        dur = ep.t_end_s - ep.t_start_s
        speed = float(ep.params.get("speed_mps", 0.9))
        self.walker: _Walker | None = None
        self.point: np.ndarray | None = None
        if ep.kind == MOTION:
            zone = ep.params.get("zone")
            region = scn.zones[zone] if zone in scn.zones else (0.0, w, 0.0, d)
            self.walker = _Walker(rng, region, speed, dur)
        elif ep.kind == NEAR_SENSOR_OUTSIDE:
            px, py = ep.params.get("point", (w + 0.8, d / 2))
            self.walker = _Walker(rng, (px - 0.5, px + 0.5, py - 0.5, py + 0.5), speed * 0.7, dur)
        elif ep.kind == STILL_PERSON:
            px, py = ep.params.get("position", (rng.uniform(0.5, w - 0.5), rng.uniform(0.5, d - 0.5)))
            self.point = np.array([float(px), float(py), BODY_HEIGHT_M])
        elif ep.kind == DOOR:
            hx, hy = ep.params.get("hinge", (w / 3, 0.0))
            self.point = np.array([float(hx), float(hy), BODY_HEIGHT_M])

    def scatterer(self, t: float) -> tuple[np.ndarray | None, float]:
        """(scatterer position, extra path length in metres) at time t."""
        t_rel = t - self.ep.t_start_s
        if self.walker is not None:
            return self.walker.position(t_rel), 0.0
        if self.ep.kind == STILL_PERSON and self.point is not None:
            # ~3 mm breathing-like displacement at 0.25 Hz: tiny and slow.
            return self.point, 0.003 * math.sin(2 * math.pi * 0.25 * t_rel)
        if self.ep.kind == DOOR and self.point is not None:
            dur = self.ep.t_end_s - self.ep.t_start_s
            theta = (math.pi / 2) * math.sin(math.pi * min(max(t_rel / dur, 0.0), 1.0))
            leaf = self.point + 0.45 * np.array([math.cos(theta), math.sin(theta), 0.0])
            return leaf, 0.0
        return None, 0.0


def _dynamic_response(link: _LinkModel, states: list[_EpisodeState], t: float, f: np.ndarray) -> tuple[np.ndarray, float]:
    """Sum of episode-driven paths for this link, and the LoS shadowing factor."""
    total = np.zeros(f.shape, dtype=np.complex128)
    los_factor = 1.0
    for st in states:
        kind = st.ep.kind
        if kind not in (MOTION, NEAR_SENSOR_OUTSIDE, STILL_PERSON, DOOR) or link.link_id not in st.links:
            continue
        pos, extra = st.scatterer(t)
        if pos is None:
            continue
        d_seg = _dist_point_segment(pos, link.tx, link.rx)
        sigma = 1.5 if kind == DOOR else 1.2
        amp = link.a_los * SCATTER_COEFF * st.strength * math.exp(-d_seg / sigma)
        path_len = float(np.linalg.norm(pos - link.tx) + np.linalg.norm(link.rx - pos)) + extra
        amps = [amp * np.exp(1j * st.phase)]
        delays = [path_len / SPEED_OF_LIGHT]
        if kind in (MOTION, NEAR_SENSOR_OUTSIDE):
            # Limb/torso micro-motion: a weaker path swinging ~8 cm at ~1.8 Hz.
            swing = 0.08 * math.sin(2 * math.pi * 1.8 * (t - st.ep.t_start_s))
            amps.append(0.35 * amp * np.exp(1j * (st.phase + 1.0)))
            delays.append((path_len + swing) / SPEED_OF_LIGHT)
        if kind != DOOR:
            los_factor *= 1.0 - min(0.6, 0.5 * st.strength) * math.exp(-((d_seg / 0.3) ** 2))
        total += _paths(np.asarray(amps), np.asarray(delays), f)
    return total, max(los_factor, 0.2)


