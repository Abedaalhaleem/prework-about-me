def zone_session_scenario(
    label: str,
    *,
    seed: int,
    duration_s: float = 60.0,
    links: list[tuple[str, str]] | None = None,
    rate_hz: float = 25.0,
    environment_seed: int = ZONES_ENVIRONMENT_SEED,
) -> SyntheticScenario:
    """A single-label SIMULATED session for zone-estimation SOFTWARE TESTS.

    ``label`` is a zone id from :data:`SYNTHETIC_ZONES`, ``"EMPTY"`` or
    ``"OUTSIDE_TARGET_ROOM"``. All sessions share one simulated environment
    (``environment_seed``) and differ in walker paths and noise (``seed``).
    """
    use_links = list(links) if links is not None else list(ZONES_3RX_LINKS)
    if label in SYNTHETIC_ZONES:
        ep = Episode(0, duration_s, MOTION, {"zone": label, "label": label})
    elif label == "EMPTY":
        ep = Episode(0, duration_s, EMPTY, {"label": "EMPTY"})
    elif label == "OUTSIDE_TARGET_ROOM":
        ep = Episode(0, duration_s, NEAR_SENSOR_OUTSIDE, {"point": OUTSIDE_POINT_3RX, "label": label})
    else:
        raise ValueError(f"unknown zone session label {label!r}; use {sorted(SYNTHETIC_ZONES)}, EMPTY or OUTSIDE_TARGET_ROOM")
    positions = {k: v for k, v in ZONES_3RX_POSITIONS.items()}
    return SyntheticScenario(
        name=f"zone_session_{label}_{seed}",
        duration_s=duration_s,
        rate_hz=rate_hz,
        links=use_links,
        episodes=[ep],
        seed=seed,
        node_positions=positions,
        description=f"SIMULATED single-label session '{label}' for software tests.",
        params={"environment_seed": environment_seed},
    )


