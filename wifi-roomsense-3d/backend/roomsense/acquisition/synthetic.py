"""SIMULATOR: synthetic CSI-shaped data. NOT a measurement of anything.

This module generates CSI-like int8 values from a deliberately simple,
physics-inspired toy model so the rest of the software (parsing-free paths,
windowing, detection state machines, UI, recording/replay) can be exercised
without hardware. Every frame it produces is labelled
``source_mode=SIMULATION``, ``input_format=synthetic-v1``, quality flag
``SYNTHETIC`` and ``device.identity_source='synthetic'`` with
``chip='synthetic'``. Results obtained on this data show that code paths
run; they say nothing about how well Wi-Fi sensing works in a real room.

The toy model (per link, per packet):

* static multipath ``H0(f) = sum_p a_p * exp(-j*2*pi*f*tau_p)`` with a
  line-of-sight path and a few reflections;
* ``MOTION``: a moving scatterer (a simulated walker in room coordinates)
  adds a path TX -> walker -> RX whose delay and amplitude change smoothly;
  its strength falls off with the walker's distance from the TX-RX segment,
  and a walker close to the line of sight also shadows it;
* ``STILL_PERSON``: a new *static* path plus a tiny slow (breathing-like)
  modulation. A variance-based motion detector is expected NOT to fire; this
  documents a known limitation, it is not a bug in the detector;
* ``DOOR``: a short, strong burst from a swinging door leaf;
* ``NEAR_SENSOR_OUTSIDE``: a walker near a point outside the target room,
  close to a sensor, strongly modulating the links near it (another known
  limitation: motion near a sensor outside the room also changes the CSI);
* ``PACKET_LOSS`` drops a fraction of packets (counter gaps);
* ``DISCONNECT`` stops a link entirely for the interval;
* plus AWGN, per-packet gain jitter, a random common phase and timing
  offset per packet (as real ESP32 CSI has), timing jitter, quantisation and
  clipping to int8.

Everything is deterministic for a given seed (numpy ``Generator`` streams
derived from the seed). The static environment uses ``environment_seed``
(default: the scenario seed) so that several sessions can share one simulated
room, e.g. for zone-estimation *software tests*.
"""

