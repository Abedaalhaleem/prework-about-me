def _link_stream(
    scn: SyntheticScenario,
    link: _LinkModel,
    states: list[_EpisodeState],
    session_id: str,
    start_mono: int,
    start_unix: int,
    time_scale: float,
) -> Iterator[tuple[float, CsiFrame]]:
    carrier = float(scn.params.get("carrier_hz", DEFAULT_CARRIER_HZ))
    noise_std = float(scn.params.get("noise_std", 0.6))
    gain_jitter = float(scn.params.get("gain_jitter", 0.03))
    timing_jitter_s = float(scn.params.get("timing_jitter_ms", 1.0)) / 1000.0
    f = carrier + _K_VALID * SUBCARRIER_SPACING_HZ
    k = _K_VALID
    noise_rng = np.random.default_rng([scn.seed, 2, link.index])
    loss_rng = np.random.default_rng([scn.seed, 3, link.index])
    time_rng = np.random.default_rng([scn.seed, 4, link.index])
    counter_unwrap = CounterUnwrapper(bits=32)
    ts_unwrap = TimestampUnwrapper()
    period = 1.0 / scn.rate_hz
    n_packets = int(math.floor(scn.duration_s * scn.rate_hz))
    identity = DeviceIdentity(
        receiver_id=link.rx_id,
        chip="synthetic",
        firmware_name="roomsense-synthetic-generator",
        firmware_version=SYNTHETIC_MODEL_VERSION,
        identity_source="synthetic",
    )
    static_eps = [st for st in states if st.ep.kind in (DISCONNECT, PACKET_LOSS)]
    guard = period / (2 * (len(scn.links) + 1))

    for n in range(n_packets):
        t_nom = n * period + link.offset_s
        # Consume the random streams for every packet, even dropped ones, so
        # an episode's randomness never depends on what happened earlier.
        air_jitter = float(np.clip(time_rng.normal(0.0, 0.0003), -guard / 4, guard / 4))
        latency = 0.002 + min(abs(float(time_rng.normal(0.0, timing_jitter_s))), guard)
        u_loss = float(loss_rng.random())
        noise = noise_rng.normal(0.0, noise_std, (2, k.size))
        g = 1.0 + float(noise_rng.normal(0.0, gain_jitter))
        common_phase = float(noise_rng.uniform(0.0, 2 * np.pi))
        timing_offset = float(noise_rng.normal(0.0, 25e-9))
        rssi_noise = float(noise_rng.normal(0.0, 0.7))

        t_rf = t_nom + air_jitter
        if t_rf >= scn.duration_s:
            break
        dropped = False
        for st in static_eps:
            if link.link_id in st.links and st.ep.active(t_rf):
                if st.ep.kind == DISCONNECT or u_loss < st.fraction:
                    dropped = True
        if dropped:
            continue

        active = [st for st in states if st.ep.active(t_rf)]
        dyn, los_factor = _dynamic_response(link, active, t_rf, f)
        h = _static_response(link, f, los_factor=los_factor) + dyn
        h = h * link.gain * g * np.exp(1j * (common_phase - 2 * np.pi * k * SUBCARRIER_SPACING_HZ * timing_offset))
        h = h + noise[0] + 1j * noise[1]
        re = np.rint(h.real)
        im = np.rint(h.imag)
        saturated = bool(np.any((re > 127) | (re < -128) | (im > 127) | (im < -128)))
        raw = np.zeros(SYNTHETIC_LAYOUT.total_values, dtype=np.int64)
        raw[2 * _VALID_POS] = np.clip(im, -128, 127).astype(np.int64)  # imaginary first (ESP-IDF order)
        raw[2 * _VALID_POS + 1] = np.clip(re, -128, 127).astype(np.int64)

        power = float(np.mean(np.abs(h / (link.gain * g)) ** 2))
        rssi = int(round(link.base_rssi + 10 * math.log10(max(power, 1e-12) / max(link.h0_power, 1e-12)) + rssi_noise))
        rssi = int(np.clip(rssi, -100, -10))

        flags: list[str] = [QualityFlag.SYNTHETIC.value]
        counter_raw = (link.counter0 + n) & 0xFFFFFFFF
        counter_unw, cflags = counter_unwrap.update(counter_raw)
        flags.extend(cflags)
        dev_raw = (link.dev0_us + int(round(t_rf * 1e6 * (1.0 + link.drift_ppm * 1e-6)))) & 0xFFFFFFFF
        dev_unw, tflags = ts_unwrap.update(dev_raw)
        flags.extend(tflags)
        if saturated:
            flags.append(QualityFlag.SATURATED_VALUES.value)

        t_host = t_rf + latency
        host_off = int(round(t_host * time_scale * 1e9))
        frame = CsiFrame(
            source_mode=SourceMode.SIMULATION,
            session_id=session_id,
            receiver_id=link.rx_id,
            transmitter_id=link.tx_id,
            link_id=link.link_id,
            input_format=InputFormat.SYNTHETIC_V1,
            device=identity,
            frame_counter=counter_raw,
            frame_counter_unwrapped=counter_unw,
            transmitter_counter=None,
            device_timestamp_us=dev_raw,
            device_timestamp_unwrapped_us=dev_unw,
            host_arrival_monotonic_ns=start_mono + host_off,
            host_arrival_unix_ns=start_unix + host_off,
            transmitter_mac=None,
            channel=SYNTHETIC_CHANNEL,
            secondary_channel=0,
            bandwidth_mhz=20,
            sig_mode=None,
            bb_format=None,
            mcs=None,
            rate=None,
            stbc=None,
            rssi_dbm=rssi,
            noise_floor_dbm=None,
            agc_gain=None,
            fft_gain=None,
            sig_len=None,
            rx_state=None,
            antenna=None,
            first_word_invalid=False,
            csi_len=SYNTHETIC_LAYOUT.total_values,
            raw_csi=tuple(raw.tolist()),
            values_are_gain_compensated=False,
            layout_id=SYNTHETIC_LAYOUT.layout_id,
            valid_subcarriers=_VALID_SUBCARRIERS,
            quality_flags=tuple(flags),
        )
        yield t_host, frame


def _link_events(scn: SyntheticScenario, start_mono: int, time_scale: float) -> list[tuple[float, LinkEvent]]:
    events: list[tuple[float, LinkEvent]] = []

    def ev(t: float, link_id: str, kind: str, detail: str) -> tuple[float, LinkEvent]:
        rx = link_id.split("->", 1)[1]
        return t, LinkEvent(
            link_id=link_id,
            receiver_id=rx,
            kind=kind,
            detail=detail,
            host_monotonic_ns=start_mono + int(round(t * time_scale * 1e9)),
            data={"simulated": True},
        )

    for lid in scn.link_ids():
        events.append(ev(0.0, lid, CONNECTED, "simulated link"))
    for ep in scn.episodes:
        if ep.kind != DISCONNECT:
            continue
        for lid in scn.affected_links(ep):
            events.append(ev(ep.t_start_s, lid, DISCONNECTED, "simulated disconnect"))
            if ep.t_end_s < scn.duration_s:
                events.append(ev(ep.t_end_s, lid, CONNECTED, "simulated reconnect"))
    events.sort(key=lambda x: x[0])
    return events


def _timeline(
    scn: SyntheticScenario,
    session_id: str,
    start_mono: int,
    start_unix: int,
    time_scale: float,
    include_events: bool,
) -> Iterator[tuple[float, CsiFrame | LinkEvent]]:
    carrier = float(scn.params.get("carrier_hz", DEFAULT_CARRIER_HZ))
    links = [_build_link(scn, i, carrier) for i in range(len(scn.links))]
    states = [_EpisodeState(scn, i, ep) for i, ep in enumerate(scn.episodes)]
    streams: list[Iterator[tuple[float, Any]]] = [
        _link_stream(scn, lk, states, session_id, start_mono, start_unix, time_scale) for lk in links
    ]
    if include_events:
        streams.append(iter(_link_events(scn, start_mono, time_scale)))
    yield from heapq.merge(*streams, key=lambda item: item[0])


def generate_frames(
    scenario: SyntheticScenario,
    session_id: str,
    *,
    start_unix_ns: int | None = None,
    start_monotonic_ns: int | None = None,
) -> Iterator[CsiFrame]:
    """Offline, deterministic SIMULATED frames in host-arrival order.

    Host timestamps start at fixed arbitrary epochs unless given, so the
    same scenario and seed always produce identical frames.
    """
    mono = SYNTHETIC_EPOCH_MONOTONIC_NS if start_monotonic_ns is None else int(start_monotonic_ns)
    unix = SYNTHETIC_EPOCH_UNIX_NS if start_unix_ns is None else int(start_unix_ns)
    for _, item in _timeline(scenario, session_id, mono, unix, 1.0, include_events=False):
        yield item  # type: ignore[misc]


class SyntheticSource(FrameSource):
    """``SIMULATION`` source. Every frame is flagged ``SYNTHETIC``.

    ``realtime=True`` emits at scenario time divided by ``speed`` and stamps
    host times accordingly. ``realtime=False`` emits as fast as possible
    (for tests); host times then follow the simulated timeline from the start
    instant, not the wall clock.
    """

    mode = SourceMode.SIMULATION

    def __init__(
        self, scenario: SyntheticScenario, *, session_id: str, realtime: bool = True, speed: float = 1.0
    ) -> None:
        if not (0 < speed <= 1000):
            raise ValueError("speed must be in (0, 1000]")
        self.scenario = scenario
        self.session_id = session_id
        self.realtime = realtime
        self.speed = float(speed)
        self._stop = threading.Event()
        self._thread: threading.Thread | None = None
        self._lock = threading.Lock()
        self.frames_emitted = 0
        self.finished = False

    def start(self, sink: Sink) -> None:
        with self._lock:
            if self._thread is not None:
                raise RuntimeError("SyntheticSource can only be started once")
            self._thread = threading.Thread(target=self._run, args=(sink,), name="synthetic", daemon=True)
            self._thread.start()

    def stop(self, timeout_s: float = 5.0) -> None:
        self._stop.set()
        t = self._thread
        if t is not None and t is not threading.current_thread():
            t.join(max(0.0, timeout_s))

    def link_ids(self) -> list[str]:
        return self.scenario.link_ids()

    def describe(self) -> dict[str, Any]:
        s = self.scenario
        return {
            "mode": self.mode.value,
            "session_id": self.session_id,
            "simulated": True,
            "banner": SIMULATED_BANNER,
            "scenario": s.name,
            "description": s.description,
            "duration_s": s.duration_s,
            "rate_hz": s.rate_hz,
            "seed": s.seed,
            "links": s.link_ids(),
            "realtime": self.realtime,
            "speed": self.speed,
            "model": SYNTHETIC_MODEL_VERSION,
            "frames_emitted": self.frames_emitted,
            "finished": self.finished,
        }

    def _run(self, sink: Sink) -> None:
        start_mono = time.monotonic_ns()
        start_unix = time.time_ns()
        scale = (1.0 / self.speed) if self.realtime else 1.0
        try:
            for t, item in _timeline(self.scenario, self.session_id, start_mono, start_unix, scale, True):
                if self._stop.is_set():
                    return
                if self.realtime:
                    remaining = (start_mono + t * scale * 1e9 - time.monotonic_ns()) / 1e9
                    if remaining > 0 and self._stop.wait(remaining):
                        return
                if isinstance(item, CsiFrame):
                    self.frames_emitted += 1
                    self._deliver(sink, FrameEvent(item))
                else:
                    self._deliver(sink, item)
        except Exception as exc:  # never let the thread die silently
            log.exception("synthetic generator failed")
            self._deliver(sink, EndOfStream(f"ERROR: {type(exc).__name__}: {exc}"[:300]))
            return
        if not self._stop.is_set():
            self.finished = True
            self._deliver(sink, EndOfStream("END_OF_SCENARIO"))

    @staticmethod
    def _deliver(sink: Sink, ev: Any) -> None:
        try:
            sink(ev)
        except Exception:
            log.exception("synthetic sink failed")


def with_seed(scenario: SyntheticScenario, seed: int) -> SyntheticScenario:
    """Copy of ``scenario`` with another seed.

    The simulated environment (static multipath, clocks) is kept: only walker
    paths, packet loss and noise change. Pass ``environment_seed`` in
    ``params`` yourself to simulate a different room.
    """
    params = dict(scenario.params)
    params.setdefault("environment_seed", scenario.seed)
    return dataclasses.replace(scenario, seed=int(seed), params=params)
